/** HTML 转义。说明里可能有 < > &，直接拼进字符串会把页面弄坏。 */
export function escapeHtml(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

/** 把 {S} 换成当前称呼。默认「她」。 */
export function withPronoun(text, she = '她') {
  // 用 split/join 而不是 replace(正则, she)：替换串里一旦出现 `$&` 这类字符，
  // String.replace 会把它当模式展开，称呼就变成了别的东西。
  return String(text ?? '').split('{S}').join(String(she || '她'))
}

