/* 历史：STACK 里放的是「来过的页」，不包含当前这一页。
   顺着点进去时把上一页压进去；点「← 上一页」时先把 SKIP 立起来，
   那一跳到站后把来路弹掉（否则再点一次又会往前跳）。 */
var TRAIL=[],SKIP=false,LAST=null;
function station(id){
  var prev='';
  if(SKIP){
    SKIP=false;
    if(TRAIL.length)TRAIL.pop();
    prev=TRAIL.length?TRAIL[TRAIL.length-1]:'';
  }else{
    prev=LAST===null?'':LAST;
    if(LAST!==null&&id!==LAST){TRAIL.push(LAST);if(TRAIL.length>30)TRAIL.shift()}
  }
  LAST=id;
  return prev;
}
