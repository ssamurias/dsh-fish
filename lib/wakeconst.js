/**
 * 空白屋子第一次醒来时的触发语（2026-10-27 用户反馈）。
 *
 * 这条路径（`wakeIfBlank`，启动时发现会话还是空的）不经过 `wake()`，
 * 没有 `fish:wake` 段可写处境——她只看见「（醒一醒）」，于是自己猜
 * 「大概不是我的时段」，还以为权限出了问题。把时间与缘由直接写进这一句：
 * 仍然是旁白、不是剧本，只是把「发生了什么事」说完整。
 *
 * 2026-11-02（用户 m00324）加 `rotated`：**换会话不是搬屋子。**
 * 满 40 轮换掉的是这一条对话记录，屋子（事件流、天数、她说过的每句话）
 * 一个字都没动。可原来四个调用方共用同一句「屋子刚建好」，轮换时她也读到
 * 这句，等于每换一次对话就告诉她「你是新的、这里是新的地方」——
 * 用户的原话是「换对话还是同一个大肥鱼、同一间屋子，不要让她以为自己是新的一条鱼」。
 * 所以轮换走单独一条措辞：明说换了什么（对话）、没换什么（屋子、她）。
 * 启动 / 重置 / 重建三条仍走「屋子刚建好」——那里本来就真的是新屋子。
 */
export function freshWakeText(now = new Date(), { rotated = false } = {}) {
  const d = now instanceof Date ? now : new Date(now)
  const t = `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`
  if (rotated === true) {
    return `（醒一醒。现在是 ${t}，对话换了一条新的，屋子还是原来那间——你没被换掉，也没搬家。之前的事都还在。）`
  }
  return `（醒一醒。现在是 ${t}，屋子刚建好，有人叫了你一声。）`
}
